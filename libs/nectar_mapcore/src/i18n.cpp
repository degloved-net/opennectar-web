const std::unordered_map<std::string_view, const char*>& englishTable()
{
	static const std::unordered_map<std::string_view, const char*> map = [] {
		std::unordered_map<std::string_view, const char*> m;
		for (const Pair& p : kTable) m.emplace(p.es, p.en);
		return m;
	}();
	return map;
}

